  const STR = { en: EN, zh: ZH, ja: JA, ko: KO, de: DE, fr: FR, es: ES, ru: RU };

  let lang;
  try {
    const saved = localStorage.getItem(KEY);
    lang = LIST.indexOf(saved) >= 0 ? saved : "en";
  } catch (e) { lang = "en"; }

  function t(key, vars) {
    const table = STR[lang] || EN;
    let s = table[key];
    if (s == null) s = EN[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
    return s;
  }

  function apply() {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
    document.title = lang === "zh" ? "Consort · FM-1 伴侣" : "Consort · FM-1 companion";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    const sel = document.getElementById("lang-select");
    if (sel) sel.value = lang;
    document.dispatchEvent(new CustomEvent("consort:lang", { detail: lang }));
  }

  function set(l) {
    lang = LIST.indexOf(l) >= 0 ? l : "en";
    try { localStorage.setItem(KEY, lang); } catch (e) { /* private mode */ }
    apply();
  }

  window.T = t;
  window.ConsortI18n = { get lang() { return lang; }, t, set, apply, list: LIST };

  const select = document.getElementById("lang-select");
  if (select) {
    select.value = lang;
    select.addEventListener("change", () => set(select.value));
  }
  apply();
